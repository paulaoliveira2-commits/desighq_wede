let dia = prompt ("Escolha um dia da semana\nSendo 1:Domingo - 7:Sábado")
switch(dia){
    case 1: alert("Voce escolheu dormingo");
    case 2: alert("Voce escolheu segunda");
    case 1: alert("Voce escolheu dormingo");
}

if (dia <=0 || dia >=8){
    alert("Dia inválido");
}else if(dia == 1){
    alert("Voce escolheu dormingo")
}else if(dia == 2){
    alert("Voce escolheu segunda")
}else if(dia == 3){
    alert("Voce escolheu terça")
}else if(dia == 4){
    alert("Voce escolheu quarta")
}else if(dia == 5){
    alert("Voce escolheu quinta ")
}else if(dia == 6){
    alert("Voce escolheu sexta")
}